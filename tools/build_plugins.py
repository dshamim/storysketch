#!/usr/bin/env python3
"""Rebuild plugins/manifest.js — the index of plugin files the tool loads.

A web page opened from disk can't list a folder, so after adding, removing or editing plugin
files run this (or use "Rescan plugins" inside the tool):

    python3 tools/build_plugins.py            # rewrite manifest.js
    python3 tools/build_plugins.py --check    # exit 1 if it is out of date (CI)

.js files are listed (they load on refresh; edits to them need no rescan);
.json files are embedded (edits to them DO need a rescan).
The output is identical to the in-app rescan (js/registry.js manifestText()).
"""
import json, os, sys

ORDER = ['styles', 'rigs', 'projects', 'hair', 'clothes', 'accessories', 'addons', 'props', 'poses', 'templates', 'characters']
here = os.path.dirname(os.path.abspath(__file__))
args = [a for a in sys.argv[1:] if not a.startswith('--')]
check = '--check' in sys.argv  # don't write: exit 1 if manifest.js is out of date (used by CI / npm run check:plugins)
root = os.path.normpath(args[0] if args else os.path.join(here, '..', 'plugins'))

files = []
for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = [d for d in dirnames if not d.startswith('.')]
    rel_dir = os.path.relpath(dirpath, root).replace(os.sep, '/')
    if rel_dir == '.':
        continue  # only files inside a type folder
    for name in filenames:
        if name.startswith('.'):
            continue
        path = f'{rel_dir}/{name}'
        if name.lower().endswith('.js'):
            files.append({'path': path})
        elif name.lower().endswith('.json'):
            with open(os.path.join(dirpath, name), encoding='utf-8') as f:
                files.append({'path': path, 'text': f.read()})

def rank(p):
    top = p['path'].split('/')[0]
    return (ORDER.index(top) if top in ORDER else 99, p['path'])

files.sort(key=rank)
# match JSON.stringify(obj, null, 1) from the browser
body = json.dumps({'files': files}, indent=1, ensure_ascii=False)
out = '// Generated by "Rescan plugins" / tools/build_plugins.py — do not edit by hand.\n' + f'CP.setManifest({body});\n'
target = os.path.join(root, 'manifest.js')
if check:
    current = open(target, encoding='utf-8').read() if os.path.exists(target) else ''
    if current != out:
        print('manifest.js is out of date — run: python3 tools/build_plugins.py', file=sys.stderr); sys.exit(1)
    print(f'manifest.js is up to date ({len(files)} files)'); sys.exit(0)
with open(target, 'w', encoding='utf-8') as f:
    f.write(out)
counts = {}
for p in files:
    counts[p['path'].split('/')[0]] = counts.get(p['path'].split('/')[0], 0) + 1
print(f'manifest.js: {len(files)} files', counts)
