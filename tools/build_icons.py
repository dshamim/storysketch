here = os.path.dirname(os.path.abspath(__file__)); root = os.path.normpath(os.path.join(here, '..'))
vendor = os.path.join(root, 'vendor', 'lucide'); out_path = os.path.join(root, 'src', 'ui', 'icons.js')

def inner(svg_text):
    """The shapes inside Lucide's <svg>…</svg>, one line, without comments."""
    s = re.sub(r'<!--.*?-->', '', svg_text, flags=re.S)
    m = re.search(r'<svg\b[^>]*>(.*)</svg>', s, flags=re.S)
    if not m: raise SystemExit('not an svg')
    body = re.sub(r'\s+', ' ', m.group(1)).strip().replace('> <', '><')
    if re.search(r'<(script|style|foreignObject|image)\b|\son\w+=', body, flags=re.I): raise SystemExit('refusing an svg with scripts/styles')
    return body

def build():
    names = {}
    for ours, lucide in ICONS.items():
        f = os.path.join(vendor, lucide + '.svg')
        if not os.path.exists(f): raise SystemExit(f'missing vendor/lucide/{lucide}.svg (icon "{ours}") — run with --vendor first')
        names[ours] = inner(open(f, encoding='utf-8').read())
    lines = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in sorted(names.items()))
    return ('// Generated by tools/build_icons.py — do not edit by hand.\n'
            '// Icons are Lucide (ISC licence, see vendor/lucide/LICENSE). Each value is the markup inside a 24×24 icon.\n'
            f'window.UI_ICONS = {{\n{lines}\n}};\n')

if '--vendor' in sys.argv:
    src = sys.argv[sys.argv.index('--vendor') + 1]
    os.makedirs(vendor, exist_ok=True)
    for lucide in sorted(set(ICONS.values())):
        shutil.copyfile(os.path.join(src, lucide + '.svg'), os.path.join(vendor, lucide + '.svg'))
    lic = os.path.join(os.path.dirname(src.rstrip('/')), 'LICENSE')
    if os.path.exists(lic): shutil.copyfile(lic, os.path.join(vendor, 'LICENSE'))
    print(f'vendored {len(set(ICONS.values()))} icons into vendor/lucide/')
out = build()
if '--check' in sys.argv:
    cur = open(out_path, encoding='utf-8').read() if os.path.exists(out_path) else ''
    if cur != out: print('src/ui/icons.js is out of date — run: python3 tools/build_icons.py', file=sys.stderr); sys.exit(1)
    print(f'icons.js is up to date ({len(ICONS)} icons)'); sys.exit(0)
open(out_path, 'w', encoding='utf-8').write(out); print(f'wrote src/ui/icons.js ({len(ICONS)} icons)')
